# =============================================================================
# utils/short.py —— 短码生成（整个短链服务的核心工具）
# =============================================================================
# 【它在链路里的位置】
#   api/short.py 创建短链时调 generate_short_tag() 生成 8 位短码
#   → 拼成 short_url 存库
#   → 用户访问 /{短码} 时再拿它去库里反查长链接
#
# 【为什么用 secrets 而不是 random】
#   random 是伪随机，能被预测（给定种子/序列可推算出后续值）。
#   短码如果可预测 = 别人能猜出你还没创建过的短链地址，甚至遍历全站。
#   secrets 用的是操作系统级熵源（密码学安全），专用于令牌/密码/短码这类场景。
#
# 【8 位够不够】
#   62^8 ≈ 218 万亿种组合，对练手项目完全够。
#   但 ★ 这段代码没做"短码冲突检测"：如果随机撞了已有短码，
#   数据库里 short_tag 又没有唯一索引（见 models/model.py），就会存进两条一样的。
#   生产做法：short_tag 加 UNIQUE 约束，插入失败就重试生成。
# =============================================================================
import secrets
import string

# 62 个字符：大小写字母 + 数字（无特殊符号，方便贴进聊天软件/二维码）
ALPHABET = string.ascii_letters + string.digits     # 62 个字符


def generate_short_tag() -> str:
    # secrets.choice 每次从 62 个字符里密码学安全地随机挑一个，重复 8 次
    return "".join(secrets.choice(ALPHABET) for _ in range(8))